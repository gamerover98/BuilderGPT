#!/usr/bin/env node
/**
 * `resources/block_states.json` -> the generated table in
 * `src/shared/block_states.ts`.
 *
 * Idempotent: running it with nothing new prints "already matches" and writes
 * no bytes. If it rewrites the file every time, the ordering or the formatting
 * has drifted, and that is the bug rather than the diff.
 *
 * Only the rows between the two markers are replaced. Everything else in
 * `block_states.ts` -- the lookups, the exclusion policy and the prose saying
 * why `waterlogged` is not there -- is hand-written and must stay that way.
 *
 * The same arrangement as `gen-mc-versions.mjs`, for the same reason: the data
 * is looked up and vendored with provenance, and the code around it is not.
 *
 * See `.claude/skills/mc-blockstates` for how the JSON is refreshed.
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA = path.join(root, "resources", "block_states.json");
const TARGET = path.join(root, "src", "shared", "block_states.ts");
const BLOCK_LIST = path.join(root, "block_id_list.txt");

const BEGIN = "// --- generated by scripts/gen-block-states.mjs -- do not edit below ---------";
const END = "// --- end generated ---------------------------------------------------------";

/**
 * Properties left out of the *default* state a placed block carries.
 *
 * `waterlogged` is the whole list, and the evidence is in `legacy_blocks.json`:
 * it maps `85:0` to `oak_fence[east=false,south=false,north=false,west=false]`
 * -- four connections and no `waterlogged`. The MCEdit writer matches a block's
 * exact state against that table, so writing the connections *improves* the
 * legacy match while writing `waterlogged=false` breaks it on every stair,
 * slab, fence, wall and pane in the build.
 *
 * It also carries nothing anyone hand-edits and did not exist before 1.13.
 *
 * Excluded from the default only. It stays in the legal values, because the
 * inspector should still offer it to somebody who wants it, and a file that
 * arrives carrying it keeps it -- this decides what a *new* block is born with,
 * not what a block may hold.
 */
const EXCLUDED_FROM_DEFAULT = new Set(["waterlogged"]);

function readJson(file) {
  return JSON.parse(readFileSync(file, "utf8"));
}

/** Stable key for a block's whole state description, for grouping. */
function signature(values, defaults) {
  const ordered = (obj) =>
    Object.fromEntries(Object.keys(obj).sort().map((key) => [key, obj[key]]));
  return JSON.stringify([ordered(values), ordered(defaults)]);
}

function quote(text) {
  return JSON.stringify(text);
}

/** A record literal with its keys already sorted, one per line. */
function recordLiteral(entries, indent) {
  const pad = " ".repeat(indent);
  return entries.map(([key, value]) => `${pad}${quote(key)}: ${value},`).join("\n");
}

function build() {
  const source = readJson(DATA);
  const blocks = source.blocks;
  const names = Object.keys(blocks).sort();

  // Group by state description. 900-odd blocks share about a hundred shapes --
  // every fence in the game has the same five properties -- so the grouped
  // table is both a third of the size and the only one a person can read.
  const shapes = [];
  const bySignature = new Map();
  const index = [];

  for (const name of names) {
    const [values, defaults] = blocks[name];
    const key = signature(values, defaults);
    let at = bySignature.get(key);
    if (at === undefined) {
      at = shapes.length;
      bySignature.set(key, at);
      shapes.push({ values, defaults });
    }
    index.push([name, at]);
  }

  const shapeLines = shapes.map(({ values, defaults }) => {
    const props = Object.keys(values).sort();
    if (props.length === 0) {
      return "  { values: {}, default: {} },";
    }
    const valueRows = props
      .map((prop) => `${quote(prop)}: [${values[prop].map(quote).join(", ")}]`)
      .join(", ");
    const defaultRows = props
      .filter((prop) => !EXCLUDED_FROM_DEFAULT.has(prop) && defaults[prop] !== undefined)
      .map((prop) => `${quote(prop)}: ${quote(defaults[prop])}`)
      .join(", ");
    return `  { values: { ${valueRows} }, default: { ${defaultRows} } },`;
  });

  const body = [
    "const SHAPES: readonly BlockStateShape[] = [",
    ...shapeLines,
    "];",
    "",
    "const BLOCK_SHAPE: Readonly<Record<string, number>> = {",
    recordLiteral(index, 2),
    "};",
  ].join("\n");

  return { body, shapes: shapes.length, blocks: names.length, names: new Set(names), source };
}

function report(names) {
  const offered = readFileSync(BLOCK_LIST, "utf8")
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("#"))
    .map((line) => line.replace(/^minecraft:/, ""));

  const missing = offered.filter((id) => !names.has(id));
  if (missing.length > 0) {
    process.stderr.write(
      `${missing.length} ids in block_id_list.txt are not in the dataset:\n  ${missing.join(" ")}\n` +
        "Read this list, do not count it. A block missing from one side is usually a\n" +
        "rename -- grass -> short_grass, grass_path -> dirt_path, sign -> oak_sign --\n" +
        "and the app deliberately keeps offering the older spelling.\n",
    );
  }
}

const { body, shapes, blocks, names, source } = build();
report(names);

const current = readFileSync(TARGET, "utf8");
const eol = current.includes("\r\n") ? "\r\n" : "\n";
const normalized = current.replace(/\r\n/g, "\n");
const begin = normalized.indexOf(BEGIN);
const end = normalized.indexOf(END);
if (begin === -1 || end === -1) {
  process.stderr.write(`markers not found in ${TARGET}\n`);
  process.exit(1);
}

const next =
  normalized.slice(0, begin + BEGIN.length) + "\n\n" + body + "\n\n" + normalized.slice(end);

if (next === normalized) {
  process.stdout.write(
    `already matches: ${blocks} blocks, ${shapes} distinct shapes, from ${source._source.minecraftVersion}\n`,
  );
  process.exit(0);
}

writeFileSync(TARGET, eol === "\r\n" ? next.replace(/\n/g, "\r\n") : next, "utf8");
process.stdout.write(
  `wrote ${blocks} blocks as ${shapes} distinct shapes, from ${source._source.minecraftVersion}\n`,
);
