/**
 * Turns `resources/block_versions.json` into the tables inside
 * `src/shared/block_versions.ts`.
 *
 *   node scripts/gen-block-versions.mjs
 *
 * Idempotent like its five siblings: running it with nothing new leaves the
 * file byte-identical, and if it rewrites every time the ordering or the
 * formatting has drifted and *that* is the bug.
 *
 * ## What this generator is actually for
 *
 * Not the transcription -- that is mechanical and dull. It is the **checks**,
 * because the data half of this dataset is derived by diffing two web sources
 * and the curated half is five renames and four value maps that nothing
 * downstream could ever contradict.
 *
 * Four of them are refusals and one is a report:
 *
 * - every `sinceDataVersion` is cross-checked against `resources/mc_versions.json`,
 *   which is the corroborated one. Two datasets naming one fact is how they come
 *   to disagree, and this check has already earned itself once, in
 *   `gen-litematica-versions.mjs`.
 * - **every rename is tied to the derived table at both ends**: the old name
 *   must have an `until` and the new one a `since`, and they must meet at the
 *   stated version. This is the tripwire that matters. A rename with a
 *   mistyped version is otherwise undetectable, and acting on it replaces every
 *   one of those blocks with empty space instead of renaming it.
 * - a `propertyValues` row may only name blocks the table has, and its maps may
 *   only name values the row itself declares.
 * - unverified rows are dropped rather than written and flagged, which is
 *   `gen-litematica-versions.mjs`'s rule: a boundary only one source claims must
 *   not reach the code that destroys blocks on the strength of it.
 * - and the report: **a block that disappears with no rename recorded**. That is
 *   either a real removal or a rename nobody has looked up yet, and the two are
 *   indistinguishable from here. The list is to be **read, not counted**.
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA = path.join(ROOT, "resources", "block_versions.json");
const VERSIONS = path.join(ROOT, "resources", "mc_versions.json");
const TARGET = path.join(ROOT, "src", "shared", "block_versions.ts");

const BEGIN = "// --- generated by scripts/gen-block-versions.mjs -- do not edit below -------";
const END = "// --- end generated ---------------------------------------------------------";

const source = JSON.parse(readFileSync(DATA, "utf8"));
const versions = JSON.parse(readFileSync(VERSIONS, "utf8")).versions ?? [];

/*
 * Labels are what a person writes in the JSON; DataVersions are what the table
 * compares. Translating here rather than in the app is what makes the
 * cross-check possible at all: a label this file cannot resolve is a refusal,
 * where a label carried through to runtime would be a silent miss.
 */
const byLabel = new Map();
for (const entry of versions) byLabel.set(entry.label, entry);

let refused = 0;
function dataVersionOf(label, why) {
  const entry = byLabel.get(label);
  if (entry === undefined) {
    console.error(`${why} names Minecraft ${label}, which resources/mc_versions.json does not have.`);
    refused += 1;
    return null;
  }
  if (entry.era !== "flat") {
    console.error(`${why} names Minecraft ${label}, which is pre-Flattening; this table is the flat era only.`);
    refused += 1;
    return null;
  }
  return entry.dataVersion;
}

// --- the derived half ------------------------------------------------------

const blocks = source.blocks ?? {};
const names = Object.keys(blocks).sort();
if (names.length === 0) {
  console.error("no blocks in resources/block_versions.json; refusing to empty the table");
  process.exit(1);
}

const rows = [];
for (const name of names) {
  const row = blocks[name];
  const since = dataVersionOf(row.since, `block ${name}`);
  const until = row.until === undefined ? null : dataVersionOf(row.until, `block ${name}`);
  if (since === null || (row.until !== undefined && until === null)) continue;
  rows.push({ name, since, until });
}

// --- renames, and the check that ties them to the table --------------------

const renames = (source.renames ?? []).filter((row) => row.verified === true);
const unverifiedRenames = (source.renames ?? []).filter((row) => row.verified !== true);

for (const row of renames) {
  const stamped = dataVersionOf(row.since, `rename ${row.from} -> ${row.to}`);
  if (stamped === null) continue;
  if (stamped !== row.sinceDataVersion) {
    console.error(
      `rename ${row.from} -> ${row.to}: this file says ${row.since} is DataVersion ` +
        `${row.sinceDataVersion}, mc_versions.json says ${stamped}. One of them is wrong ` +
        `and neither is guessable from here.`,
    );
    refused += 1;
    continue;
  }
  /*
   * Both ends, against the derived table. The old name must stop and the new
   * one must start, and they must meet exactly here -- otherwise the rename is
   * describing a boundary the registries do not have, and the app would apply
   * it at the wrong version and lose every one of those blocks.
   */
  const before = blocks[row.from];
  const after = blocks[row.to];
  if (before === undefined || before.until === undefined) {
    console.error(`rename ${row.from} -> ${row.to}: ${row.from} has no recorded end in the table.`);
    refused += 1;
    continue;
  }
  if (after === undefined) {
    console.error(`rename ${row.from} -> ${row.to}: ${row.to} is not in the table at all.`);
    refused += 1;
    continue;
  }
  if (after.since !== row.since) {
    console.error(
      `rename ${row.from} -> ${row.to}: this file says the new name starts at ${row.since}, ` +
        `the table says ${after.since}.`,
    );
    refused += 1;
    continue;
  }
  const endIndex = versions.findIndex((v) => v.label === before.until);
  const startIndex = versions.findIndex((v) => v.label === after.since);
  // MC_VERSIONS is newest-first, so the version *before* another has a larger index.
  if (endIndex <= startIndex) {
    console.error(
      `rename ${row.from} -> ${row.to}: ${row.from} ends at ${before.until} and ${row.to} ` +
        `starts at ${after.since}, which do not meet. A gap or an overlap here is a build ` +
        `that would come back with holes in it.`,
    );
    refused += 1;
  }
}

const renameRows = renames.map((row) => ({
  from: row.from,
  to: row.to,
  since: row.sinceDataVersion,
}));

// --- property events -------------------------------------------------------

const propertyRows = [];
for (const row of source.properties ?? []) {
  if (blocks[row.block] === undefined) {
    console.error(`property ${row.block}.${row.property} names a block the table does not have.`);
    refused += 1;
    continue;
  }
  const label = row.since ?? row.until;
  const stamped = dataVersionOf(label, `property ${row.block}.${row.property}`);
  if (stamped === null) continue;
  propertyRows.push({
    block: row.block,
    property: row.property,
    since: row.since === undefined ? null : stamped,
    until: row.until === undefined ? null : stamped,
  });
}
propertyRows.sort((a, b) =>
  a.block === b.block ? a.property.localeCompare(b.property) : a.block.localeCompare(b.block),
);

// --- property value maps ---------------------------------------------------

const valueRows = [];
for (const row of source.propertyValues ?? []) {
  if (row.verified !== true) continue;
  const stamped = dataVersionOf(row.since, `property values ${row.properties.join("/")}`);
  if (stamped === null) continue;
  if (stamped !== row.sinceDataVersion) {
    console.error(
      `property values ${row.properties.join("/")} at ${row.since}: this file says DataVersion ` +
        `${row.sinceDataVersion}, mc_versions.json says ${stamped}.`,
    );
    refused += 1;
    continue;
  }
  const missing = row.blocks.filter((name) => blocks[name] === undefined);
  if (missing.length > 0) {
    console.error(
      `property values ${row.properties.join("/")} at ${row.since} name blocks the table does ` +
        `not have: ${missing.join(", ")}`,
    );
    refused += 1;
    continue;
  }
  /*
   * A map may only speak about values the row itself declares. Without this, a
   * typo in a key is a mapping that silently never fires -- and the state it
   * was meant to rewrite goes into the file unchanged, which is the failure
   * this whole row exists to prevent.
   */
  const bad = [
    ...Object.keys(row.backport ?? {}).filter((k) => !row.to.includes(k)),
    ...Object.values(row.backport ?? {}).filter((v) => !row.from.includes(v)),
    ...Object.keys(row.forward ?? {}).filter((k) => !row.from.includes(k)),
    ...Object.values(row.forward ?? {}).filter((v) => !row.to.includes(v)),
  ];
  if (bad.length > 0) {
    console.error(
      `property values ${row.properties.join("/")} at ${row.since}: the maps name values the ` +
        `row does not declare: ${[...new Set(bad)].join(", ")}`,
    );
    refused += 1;
    continue;
  }
  valueRows.push({
    properties: row.properties,
    blocks: row.blocks,
    since: row.sinceDataVersion,
    backport: row.backport ?? {},
    forward: row.forward ?? {},
  });
}
valueRows.sort((a, b) =>
  a.since === b.since ? a.properties.join("/").localeCompare(b.properties.join("/")) : a.since - b.since,
);

if (refused > 0) process.exit(1);

// --- emit ------------------------------------------------------------------

const q = JSON.stringify;

/** `{}` rather than `{  }` for an empty map: this file is compared byte for byte. */
const pairs = (map) => {
  const entries = Object.entries(map).map(([k, v]) => `${q(k)}: ${q(v)}`);
  return entries.length === 0 ? "{}" : `{ ${entries.join(", ")} }`;
};
const lines = [];

lines.push("/** Every block this app knows about, and the DataVersion range it exists in. */");
lines.push("const BLOCK_RANGE: Readonly<Record<string, readonly [number, number | null]>> = {");
for (const row of rows) lines.push(`  ${q(row.name)}: [${row.since}, ${row.until ?? "null"}],`);
lines.push("};");
lines.push("");
lines.push("/** The renames, oldest first. `since` is where the *new* name starts. */");
lines.push("const RENAMES: readonly BlockRename[] = [");
for (const row of renameRows.slice().sort((a, b) => a.since - b.since)) {
  lines.push(`  { from: ${q(row.from)}, to: ${q(row.to)}, since: ${row.since} },`);
}
lines.push("];");
lines.push("");
lines.push("/** When a property arrived on a block, or left it. */");
lines.push("const PROPERTY_EVENTS: readonly PropertyEvent[] = [");
for (const row of propertyRows) {
  lines.push(
    `  { block: ${q(row.block)}, property: ${q(row.property)}, ` +
      `since: ${row.since ?? "null"}, until: ${row.until ?? "null"} },`,
  );
}
lines.push("];");
lines.push("");
lines.push("/** Properties whose legal values changed, with the map in both directions. */");
lines.push("const VALUE_CHANGES: readonly ValueChange[] = [");
for (const row of valueRows) {
  lines.push("  {");
  lines.push(`    properties: [${row.properties.map(q).join(", ")}],`);
  lines.push(`    blocks: [${row.blocks.map(q).join(", ")}],`);
  lines.push(`    since: ${row.since},`);
  lines.push(`    backport: ${pairs(row.backport)},`);
  lines.push(`    forward: ${pairs(row.forward)},`);
  lines.push("  },");
}
lines.push("];");

const body = lines.join("\n");
const current = readFileSync(TARGET, "utf8");
const eol = current.includes("\r\n") ? "\r\n" : "\n";
const normalized = current.replace(/\r\n/g, "\n");
const begin = normalized.indexOf(BEGIN);
const end = normalized.indexOf(END);
if (begin === -1 || end === -1) {
  process.stderr.write(`markers not found in ${TARGET}\n`);
  process.exit(1);
}
const next =
  normalized.slice(0, begin + BEGIN.length) + "\n\n" + body + "\n\n" + normalized.slice(end);

/*
 * The report, and it is the half of this script that needs a person.
 *
 * A block that stops existing with no rename recorded is either a real removal
 * or a rename nobody has looked up. From here the two look identical, and the
 * consequence of guessing wrong is one-directional: treat a rename as a removal
 * and every one of those blocks becomes empty space on the next backport.
 */
const renamedFrom = new Set(renames.map((row) => row.from));
const orphans = rows.filter((row) => row.until !== null && !renamedFrom.has(row.name));
if (orphans.length > 0) {
  console.error(
    `\n${orphans.length} block(s) stop existing with no rename recorded. Read this list, do not\n` +
      `count it: a disappearance is far more often a rename than a removal -- grass ->\n` +
      `short_grass, chain -> iron_chain -- and recording it as a removal is what turns a\n` +
      `backport into a demolition.\n  ` +
      orphans.map((row) => row.name).join("\n  ") +
      "\n",
  );
}
if (unverifiedRenames.length > 0) {
  console.error(
    `\n${unverifiedRenames.length} rename(s) left out for want of corroboration:\n  ` +
      unverifiedRenames.map((row) => `${row.from} -> ${row.to}`).join("\n  ") +
      "\n",
  );
}

if (next === normalized) {
  process.stdout.write(
    `already matches: ${rows.length} blocks, ${renameRows.length} renames, ` +
      `${propertyRows.length} property events, ${valueRows.length} value changes\n`,
  );
  process.exit(0);
}
writeFileSync(TARGET, eol === "\r\n" ? next.replace(/\n/g, "\r\n") : next, "utf8");
process.stdout.write(
  `wrote ${rows.length} blocks, ${renameRows.length} renames, ${propertyRows.length} property ` +
    `events and ${valueRows.length} value changes into src/shared/block_versions.ts\n`,
);
