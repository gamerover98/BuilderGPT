/**
 * Turns `resources/command_syntax.json` into the two tables inside
 * `src/shared/command_syntax.ts`.
 *
 *   node scripts/gen-command-syntax.mjs
 *
 * Idempotent, like the other three generators: running it with no new data
 * leaves the file byte-identical. Only the rows between the markers are
 * replaced -- the prose explaining why the mode word is left off, and why this
 * floor is a release earlier than the litematic one, is hand-written.
 *
 * Two blocks rather than one, because the file has two tables and a single
 * marker pair would mean deciding which one a row belongs to by parsing it.
 *
 * **Unverified rows are dropped.** For a syntax row that is nearly harmless --
 * the round trip would catch a wrong one -- and for a limit row it is the whole
 * point: nothing in this repo can observe a function being truncated at 65,536
 * commands, so a number nobody corroborated must not reach the writer.
 *
 * Like `gen-litematica-versions.mjs`, every `sinceDataVersion` is cross-checked
 * against `resources/mc_versions.json`, which is the corroborated one. Two
 * datasets naming one fact is how they come to disagree.
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA = path.join(ROOT, "resources", "command_syntax.json");
const VERSIONS = path.join(ROOT, "resources", "mc_versions.json");
const TARGET = path.join(ROOT, "src", "shared", "command_syntax.ts");

const FORMS_BEGIN = "  // <<< generated by scripts/gen-command-syntax.mjs -- do not edit by hand";
const FORMS_END = "  // >>> end generated forms";
const LIMITS_BEGIN =
  "  // <<< generated limits by scripts/gen-command-syntax.mjs -- do not edit by hand";
const LIMITS_END = "  // >>> end generated limits";

const raw = JSON.parse(readFileSync(DATA, "utf8"));
const allForms = Array.isArray(raw.forms) ? raw.forms : [];
const allLimits = Array.isArray(raw.limits) ? raw.limits : [];

const dropped = [
  ...allForms.filter((row) => row.verified !== true).map((row) => `form ${row.command}`),
  ...allLimits.filter((row) => row.verified !== true).map((row) => `limit ${row.name}`),
];
const forms = allForms.filter((row) => row.verified === true);
const limits = allLimits.filter((row) => row.verified === true);

if (forms.length === 0 || limits.length === 0) {
  console.error("resources/command_syntax.json has no verified forms or no verified limits");
  process.exit(1);
}

const byLabel = new Map();
for (const entry of JSON.parse(readFileSync(VERSIONS, "utf8")).versions ?? []) {
  byLabel.set(entry.label, entry);
}

let disagreed = 0;
for (const row of forms) {
  const entry = byLabel.get(row.since);
  if (entry === undefined) {
    console.error(`${row.command} names Minecraft ${row.since}, which mc_versions.json lacks`);
    disagreed += 1;
  } else if (entry.dataVersion !== row.sinceDataVersion) {
    console.error(
      `${row.command}: this file says ${row.since} is DataVersion ${row.sinceDataVersion}, ` +
        `mc_versions.json says ${entry.dataVersion}`,
    );
    disagreed += 1;
  }
}
if (disagreed > 0) process.exit(1);

const q = JSON.stringify;
const formLines = forms.map(
  (row) =>
    `  { command: ${q(row.command)}, syntax: ${q(row.syntax)}, since: ${q(row.since)}, ` +
    `sinceDataVersion: ${row.sinceDataVersion}, note: ${q(row.note)} },`,
);
const limitLines = limits.map(
  (row) =>
    `  { name: ${q(row.name)}, formerName: ${row.formerName === null ? "null" : q(row.formerName)}, ` +
    `renamedIn: ${row.renamedIn === null ? "null" : q(row.renamedIn)}, value: ${row.value}, ` +
    `applies: ${q(row.applies)}, note: ${q(row.note)} },`,
);

const source = readFileSync(TARGET, "utf8");
const crlf = /\r\n/.test(source);
let body = source.replace(/\r\n/g, "\n");

for (const [begin, end, lines] of [
  [FORMS_BEGIN, FORMS_END, formLines],
  [LIMITS_BEGIN, LIMITS_END, limitLines],
]) {
  const from = body.indexOf(begin);
  const to = body.indexOf(end);
  if (from === -1 || to === -1 || to < from) {
    console.error(`markers not found in ${TARGET}: ${begin.trim()}`);
    process.exit(1);
  }
  body = body.slice(0, from) + begin + "\n" + lines.join("\n") + "\n" + body.slice(to);
}

const out = crlf ? body.replace(/\n/g, "\r\n") : body;
if (out === source) {
  console.log(`command_syntax.ts already matches: ${forms.length} forms, ${limits.length} limits`);
} else {
  writeFileSync(TARGET, out);
  console.log(`wrote ${forms.length} forms and ${limits.length} limits into src/shared/command_syntax.ts`);
}

if (dropped.length > 0) {
  console.error(`\n${dropped.length} row(s) left out for want of corroboration:`);
  for (const label of dropped) console.error(`  ${label}`);
}
