/**
 * Turns `resources/litematica_versions.json` into the table inside
 * `src/shared/litematica_versions.ts`.
 *
 *   node scripts/gen-litematica-versions.mjs
 *
 * Idempotent, like `gen-mc-versions.mjs`: running it with no new data leaves
 * the file byte-identical, which is what makes it safe to run on every pass of
 * the `mc-litematic` skill. Only the rows between the two markers are replaced;
 * the prose explaining why the floor is 1.13.2 rather than 1.13 is hand-written
 * and stays hand-written.
 *
 * **Unverified rows are dropped, not written and flagged.** A schematic version
 * whose boundary only one source claims must not reach the writer: Litematica
 * reads a file according to what it says it is, and a wrong `Version` produces
 * a file that opens and comes back converted.
 *
 * ## The cross-check is the point
 *
 * Every `sinceDataVersion` here also exists in `resources/mc_versions.json`,
 * which is corroborated by two independent sources. So this generator refuses
 * on any disagreement rather than writing its own number -- two datasets naming
 * one fact is how they come to disagree, and the first draft of this file said
 * 1.18 was 2825 when the verified table says 2860. Nothing downstream would
 * have noticed: the file would have saved, opened, and been converted by
 * Litematica for anyone on 1.18.0 or 1.18.1.
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA = path.join(ROOT, "resources", "litematica_versions.json");
const VERSIONS = path.join(ROOT, "resources", "mc_versions.json");
const TARGET = path.join(ROOT, "src", "shared", "litematica_versions.ts");

const BEGIN = "  // <<< generated by scripts/gen-litematica-versions.mjs -- do not edit by hand";
const END = "  // >>> end generated";

const raw = JSON.parse(readFileSync(DATA, "utf8"));
const rows = Array.isArray(raw.versions) ? raw.versions : [];

const dropped = rows.filter((row) => row.verified !== true || row.sinceDataVersion === null);
const kept = rows
  .filter((row) => row.verified === true && row.sinceDataVersion !== null)
  .sort((a, b) => b.version - a.version);

if (kept.length === 0) {
  console.error("no verified rows in resources/litematica_versions.json; refusing to empty the table");
  process.exit(1);
}

/*
 * The same version twice would make `litematicVersionFor` depend on the sort
 * being stable, which is a property nobody would think to check.
 */
const seen = new Set();
for (const row of kept) {
  if (seen.has(row.version)) {
    console.error(`duplicate schematic version ${row.version}`);
    process.exit(1);
  }
  seen.add(row.version);
}

const byLabel = new Map();
for (const entry of JSON.parse(readFileSync(VERSIONS, "utf8")).versions ?? []) {
  byLabel.set(entry.label, entry);
}

let disagreed = 0;
for (const row of kept) {
  const entry = byLabel.get(row.since);
  if (entry === undefined) {
    console.error(
      `schematic version ${row.version} names Minecraft ${row.since}, which resources/mc_versions.json ` +
        `does not have. Add it with the mc-versions skill first.`,
    );
    disagreed += 1;
    continue;
  }
  if (entry.dataVersion !== row.sinceDataVersion) {
    console.error(
      `schematic version ${row.version}: this file says ${row.since} is DataVersion ` +
        `${row.sinceDataVersion}, mc_versions.json says ${entry.dataVersion}. One of them is wrong ` +
        `and neither is guessable from here.`,
    );
    disagreed += 1;
  }
}
if (disagreed > 0) process.exit(1);

const lines = kept.map(
  (row) =>
    `  { version: ${row.version}, subVersion: ${row.subVersion}, ` +
    `since: ${JSON.stringify(row.since)}, sinceDataVersion: ${row.sinceDataVersion}, ` +
    `note: ${JSON.stringify(row.note)} },`,
);

const source = readFileSync(TARGET, "utf8");
const crlf = /\r\n/.test(source);
const body = source.replace(/\r\n/g, "\n");

const from = body.indexOf(BEGIN);
const to = body.indexOf(END);
if (from === -1 || to === -1 || to < from) {
  console.error(`markers not found in ${TARGET}`);
  process.exit(1);
}

const next = body.slice(0, from) + BEGIN + "\n" + lines.join("\n") + "\n" + body.slice(to);
const out = crlf ? next.replace(/\n/g, "\r\n") : next;

if (out === source) {
  console.log(`litematica_versions.ts already matches: ${kept.length} versions`);
} else {
  writeFileSync(TARGET, out);
  console.log(`wrote ${kept.length} versions into src/shared/litematica_versions.ts`);
}

/*
 * To stderr and meant to be *read*, not counted. A dropped row is one somebody
 * may be waiting for, and it stays dropped silently forever if nobody looks.
 */
if (dropped.length > 0) {
  console.error(`\n${dropped.length} schematic version(s) left out:`);
  for (const row of dropped) {
    const why = row.verified !== true ? "not corroborated" : "no Minecraft release recorded";
    console.error(`  Version ${row.version} (${why})`);
  }
}
