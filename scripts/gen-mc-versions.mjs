/**
 * Turns `resources/mc_versions.json` into the table inside
 * `src/shared/mc_versions.ts`.
 *
 *   node scripts/gen-mc-versions.mjs
 *
 * Idempotent: running it with no new data leaves the file byte-identical, which
 * is what makes it safe to run on every pass of the `mc-versions` skill.
 *
 * Only the rows between the two markers are replaced. Everything else in that
 * file -- the era rule, the refusal message, the prose explaining why Sponge
 * cannot exist before the Flattening -- is hand-written and stays hand-written.
 * Generating the whole file would mean the explanation lived in a generator,
 * which is where explanations go to die.
 *
 * **Unverified entries are dropped, not written and flagged.** A version whose
 * number only one source claims must not reach the picker at all: the app
 * offers what it knows how to write correctly, and a wrong DataVersion produces
 * a file that looks right and misbehaves in game. The JSON keeps the row so the
 * next run can promote it once a second source agrees.
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA = path.join(ROOT, "resources", "mc_versions.json");
const TARGET = path.join(ROOT, "src", "shared", "mc_versions.ts");

const BEGIN = "  // <<< generated by scripts/gen-mc-versions.mjs -- do not edit by hand";
const END = "  // >>> end generated";

const raw = JSON.parse(readFileSync(DATA, "utf8"));
const versions = Array.isArray(raw.versions) ? raw.versions : [];

const dropped = versions.filter((entry) => entry.verified !== true);
const kept = versions.filter((entry) => entry.verified === true);

if (kept.length === 0) {
  console.error("no verified versions in resources/mc_versions.json; refusing to empty the table");
  process.exit(1);
}

/** Two rows claiming the same DataVersion would make `versionNameOf` a coin toss. */
const seen = new Map();
for (const entry of kept) {
  if (entry.dataVersion === null) continue;
  const first = seen.get(entry.dataVersion);
  if (first !== undefined) {
    console.error(`duplicate DataVersion ${entry.dataVersion}: ${first} and ${entry.name}`);
    process.exit(1);
  }
  seen.set(entry.dataVersion, entry.name);
}

const lines = kept.map((entry) => {
  const data = entry.dataVersion === null ? "null" : String(entry.dataVersion);
  return (
    `  { name: ${JSON.stringify(entry.name)}, label: ${JSON.stringify(entry.label)}, ` +
    `era: ${JSON.stringify(entry.era)}, dataVersion: ${data} },`
  );
});

const source = readFileSync(TARGET, "utf8");
const crlf = /\r\n/.test(source);
const body = source.replace(/\r\n/g, "\n");

const from = body.indexOf(BEGIN);
const to = body.indexOf(END);
if (from === -1 || to === -1 || to < from) {
  console.error(`markers not found in ${TARGET}`);
  process.exit(1);
}

const next =
  body.slice(0, from) + BEGIN + "\n" + lines.join("\n") + "\n" + body.slice(to);
const out = crlf ? next.replace(/\n/g, "\r\n") : next;

if (out === source) {
  console.log(`mc_versions.ts already matches: ${kept.length} versions`);
} else {
  writeFileSync(TARGET, out);
  console.log(`wrote ${kept.length} versions into src/shared/mc_versions.ts`);
}

/*
 * Printed to stderr and meant to be *read*, not counted -- the same discipline
 * `gen-block-list.mjs` applies to its plausibility check. A dropped version is
 * one somebody may be waiting for, and it will stay dropped silently forever if
 * nobody looks.
 */
if (dropped.length > 0) {
  console.error(`\n${dropped.length} version(s) left out for want of a second source:`);
  for (const entry of dropped) {
    console.error(`  ${entry.label} (${entry.dataVersion ?? "no DataVersion"})`);
  }
}
