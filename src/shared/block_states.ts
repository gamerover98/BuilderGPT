/** `minecraft:oak_stairs[facing=east]` and `oak_stairs` both come back bare. */
function bareName(id: string): string {
  const withoutState = id.split("[")[0].trim();
  const colon = withoutState.lastIndexOf(":");
  return colon === -1 ? withoutState : withoutState.slice(colon + 1);
}

function shapeOf(id: string): BlockStateShape | null {
  const at = BLOCK_SHAPE[bareName(id)];
  return at === undefined ? null : SHAPES[at];
}

/**
 * The state a freshly placed block starts in, or `{}` for a block with no
 * properties -- which is 346 of the 920 the app offers, and is a real answer
 * rather than a gap. An inspector saying "no block states" for `minecraft:stone`
 * is correct.
 *
 * A block the table does not know also comes back `{}`, which is exactly what
 * happened before this table existed. An omission costs nothing; a wrong guess
 * writes a state that is worse than none because it looks deliberate.
 */
export function defaultStateFor(id: string): Record<string, string> {
  const shape = shapeOf(id);
  return shape === null ? {} : { ...shape.default };
}

/**
 * The legal values of one property, or `null` when the app does not know.
 *
 * `null` and `[]` mean different things and the inspector treats them so: no
 * knowledge is a free-text field, while an empty list would claim the property
 * accepts nothing.
 */
export function legalValuesFor(id: string, property: string): readonly string[] | null {
  const shape = shapeOf(id);
  const values = shape?.values[property];
  return values === undefined ? null : values;
}

/** Every property a block carries, sorted. Empty for one with none. */
export function propertiesOf(id: string): readonly string[] {
  const shape = shapeOf(id);
  return shape === null ? [] : Object.keys(shape.values).sort();
}

/**
 * Whether a block carries a property at all.
 *
 * Used to decide what a rule may write: a rule that sets `north` on something
 * with no `north` produces a block state the game refuses, and nothing else in
 * this app would notice.
 */
export function hasProperty(id: string, property: string): boolean {
  const shape = shapeOf(id);
  return shape !== null && shape.values[property] !== undefined;
}

/** Whether the table knows this block at all. */
