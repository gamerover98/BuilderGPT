/**
 * What properties a block has, what values they may take, and what state it is
 * born in.
 *
 * ## Why this exists
 *
 * A block state is the part of a block that is not its name -- `facing`,
 * `half`, `north`, `age` -- and until this table the app invented them. Nothing
 * here validates a property name: the inspector shows whatever the entry has,
 * the writers put whatever they are given into the file, and the mesher ignores
 * what it does not recognise. A property written onto a block that does not
 * carry it is therefore invisible here and fatal in the game that is eventually
 * asked to paste the schematic.
 *
 * The mirror image cost more. `block_orientation.ts` carried a hand-written
 * `DEFAULT_STATE` of twenty-one families, so every other block was placed with
 * no properties at all -- an empty inspector, and, for anything
 * `block_shapes.ts` reads a property to draw, the wrong shape. A fence placed
 * by hand had no `north`, so it drew as a bare post, and the panel that exists
 * to let you fix that had nothing to show.
 *
 * ## The shape of it
 *
 * ```
 * resources/block_states.json     the data, with provenance   <- refreshed by the skill
 * scripts/gen-block-states.mjs    JSON -> the table
 * src/shared/block_states.ts      this file
 * ```
 *
 * The same arrangement as `mc_versions.json`, and for the same reason: the
 * answers are looked up, corroborated and recorded with where they came from,
 * rather than remembered. `.claude/skills/mc-blockstates` is the procedure.
 *
 * It lives in `shared/` for `block_orientation.ts`'s stated reason -- it is a
 * fact about Minecraft rather than about a process. The renderer needs it to
 * offer values in the inspector and main needs it to write a placed block, and
 * two tables would be two tables to get wrong.
 *
 * ## What is generated and what is not
 *
 * Only the rows between the two markers. The lookups below them are
 * hand-written, and so is `block_orientation.ts`, which must **not** become
 * generated: it answers which way a block placed by *this click* points, and
 * that depends on where the camera was. No dataset knows that.
 *
 * ## The dataset is pinned to a release, deliberately
 *
 * `misode/mcmeta`'s `summary` branch tracks snapshots, and on it `chain` has
 * already become `iron_chain` -- while `block_id_list.txt` still offers
 * `chain`. Pinning to 1.21.8 is what keeps the two in step; the rename landed
 * in 1.21.11. The provenance block in the JSON records this so a future refresh
 * does not "helpfully" move to the newest branch.
 */

export interface BlockStateShape {
  /** Every legal value of every property, as the game defines them. */
  readonly values: Readonly<Record<string, readonly string[]>>;
  /**
   * The state a freshly placed block carries.
   *
   * Not the same key set as `values`: `waterlogged` is deliberately absent, and
   * `scripts/gen-block-states.mjs` carries the evidence. In short,
   * `legacy_blocks.json` maps `85:0` to
   * `oak_fence[east=false,south=false,north=false,west=false]` with no
   * `waterlogged`, and the MCEdit writer matches the exact state -- so writing
   * the connections improves the legacy match and writing `waterlogged` breaks
   * it on every stair, slab, fence and pane in the build.
   *
   * It stays in `values`, because the inspector should still offer it to
   * anyone who wants it and a file that arrives carrying it keeps it. This
   * decides what a *new* block is born with, not what a block may hold.
   */
  readonly default: Readonly<Record<string, string>>;
}

