/** `minecraft:oak_stairs[facing=north]` -> `oak_stairs`. */
function bareName(id: string): string {
  let name = id;
  const bracket = name.indexOf("[");
  if (bracket !== -1) name = name.slice(0, bracket);
  return name.startsWith("minecraft:") ? name.slice("minecraft:".length) : name;
}

/**
 * Whether this build knows anything at all about when a block existed.
 *
 * Exported because "I have no idea" and "it exists everywhere" are different
 * answers that `blockExistsIn` deliberately collapses, and a caller reporting
 * to a person may want to say which it was.
 */
export function isVersioned(id: string): boolean {
  return BLOCK_RANGE[bareName(id)] !== undefined;
}

/**
 * Whether a block exists in the given version.
 *
 * Unknown blocks are present: see the header. This asks about the id **as
 * spelled**, so `chain` is absent from 1.21.9 and `iron_chain` from 1.21.8 --
 * both true, and both the wrong question to ask on its own. Ask `renameFor`
 * first.
 */
export function blockExistsIn(id: string, dataVersion: number): boolean {
  const range = BLOCK_RANGE[bareName(id)];
  if (range === undefined) return true;
  const [since, until] = range;
  return dataVersion >= since && (until === null || dataVersion <= until);
}

const blockSets = new Map<number, ReadonlySet<string>>();

/**
 * Every block this table says exists in a version, without the namespace.
 *
 * Memoised because the inventory asks per keystroke and the answer moves only
 * when the document's version does. The set is the *table's* view, so a block
 * outside it is missing from this set and still allowed by `blockExistsIn` --
 * the callers that filter a list want the narrow answer, and the caller that
 * guards a placement wants the generous one.
 */
export function blocksIn(dataVersion: number): ReadonlySet<string> {
  const held = blockSets.get(dataVersion);
  if (held !== undefined) return held;
  const set = new Set<string>();
  for (const name of Object.keys(BLOCK_RANGE)) {
    const [since, until] = BLOCK_RANGE[name];
    if (dataVersion >= since && (until === null || dataVersion <= until)) set.add(name);
  }
  blockSets.set(dataVersion, set);
  return set;
}

/**
 * What this block is called in the given version, or `null` if it is unchanged.
 *
 * Both directions from one table: an id that is a rename's old name becomes the
 * new one at or after the boundary, and an id that is the new name becomes the
 * old one before it.
 *
 * The loop is a fixed point rather than a single pass because nothing stops a
 * block being renamed twice -- none has yet, and the day one is, a single pass
 * would carry it half way and leave a name no version ever had. Bounded by the
 * table's own length, so a pair of rows that disagreed could not hang.
 */
export function renameFor(id: string, dataVersion: number): string | null {
  let name = bareName(id);
  const started = name;
  for (let pass = 0; pass <= RENAMES.length; pass += 1) {
    let moved = false;
    for (const rename of RENAMES) {
      if (name === rename.from && dataVersion >= rename.since) {
        name = rename.to;
        moved = true;
      } else if (name === rename.to && dataVersion < rename.since) {
        name = rename.from;
        moved = true;
      }
    }
    if (!moved) break;
  }
  return name === started ? null : name;
}

/**
 * Whether a block carries a property in the given version.
 *
 * A property with no recorded event is present, for the header's reason. The
 * two events are read as one-sided bounds rather than a range because a
 * property that arrived and later left would have two rows, and reading them
 * together is what keeps that case from needing a third shape.
 */
export function propertyExistsIn(id: string, property: string, dataVersion: number): boolean {
  const name = bareName(id);
  for (const event of PROPERTY_EVENTS) {
    if (event.block !== name || event.property !== property) continue;
    if (event.since !== null && dataVersion < event.since) return false;
    if (event.until !== null && dataVersion > event.until) return false;
  }
  return true;
}

/**
 * What a property's value has to become in the given version, or `null` if it
 * is already sayable there.
 *
 * `null` covers both "nothing changed" and "this value is legal on both sides",
 * which are the same instruction to a caller: leave it alone.
 */
export function propertyValueIn(
  id: string,
  property: string,
  value: string,
  dataVersion: number,
): string | null {
  const name = bareName(id);
  for (const change of VALUE_CHANGES) {
    if (!change.properties.includes(property)) continue;
    if (!change.blocks.includes(name)) continue;
    const map = dataVersion < change.since ? change.backport : change.forward;
    const mapped = map[value];
    if (mapped !== undefined && mapped !== value) return mapped;
  }
  return null;
}

/** How many blocks the table holds. For the suites, and for a sanity print. */
export function versionedBlockCount(): number {
  return Object.keys(BLOCK_RANGE).length;
}
