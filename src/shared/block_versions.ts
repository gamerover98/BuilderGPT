/**
 * What exists in which Minecraft version.
 *
 * Changing which Minecraft a schematic is for used to move the `DataVersion`
 * tag and nothing else. Only the pre-Flattening boundary was checked, because
 * `legacy_blocks.json` was the only per-block knowledge this app had -- so
 * backporting a 1.21 build to 1.13 left up to **501 kinds of block** in a file
 * for a game that has never heard of them, and upgrading a 1.16 build left
 * every `chain` under a name 1.21.9 renamed.
 *
 * ## The shape of it
 *
 * ```
 * resources/block_versions.json     the data, with provenance   ← .claude/skills/mc-block-versions
 * scripts/gen-block-versions.mjs    JSON → the tables below
 * src/shared/block_versions.ts      the tables, plus the lookups
 * ```
 *
 * It is in `shared/` for `block_orientation.ts`'s reason: the renderer has to
 * filter the inventory by what the open schematic can hold, and may not import
 * out of `main/`.
 *
 * ## A rename is not a removal, and that is the whole design
 *
 * A diff of two registries sees `chain` disappear at 1.21.9 and `iron_chain`
 * appear, and **cannot tell that from a removal plus an unrelated addition**.
 * The two answers are not near-misses of each other: read as a removal, a
 * backport across that boundary replaces every chain in the build with empty
 * space; read as a rename, it writes the name the older game uses and loses
 * nothing.
 *
 * So `renameFor` is asked **first**, and only what is left after it is a
 * candidate for being dropped. There are five renames across the whole flat
 * era and every one of them is corroborated on the wiki's History section,
 * because that link is prose and appears in no dataset.
 *
 * ## Everything unknown fails open
 *
 * A block, property or value this table has never heard of is treated as
 * present. That is `defaultStateFor`'s rule and it holds here for a sharper
 * reason: the cost of an omission is a block that survives a backport it maybe
 * should not have, and the cost of a wrong guess is a block destroyed. The two
 * are not comparable, so the doubt goes one way.
 *
 * ## DataVersions, not names
 *
 * The tables compare integers. A version *name* would have to be resolved at
 * every call, and a name this file could not resolve would silently answer "not
 * present" -- which is the one wrong answer that costs blocks. The generator
 * resolves labels against `resources/mc_versions.json` instead, and refuses
 * rather than write a number of its own.
 *
 * `dataVersion === null` -- a document that names no version -- is not a
 * question this file can answer, and callers must not ask it one.
 */

/** A block id that changed, and the DataVersion at which the new name starts. */
interface BlockRename {
  readonly from: string;
  readonly to: string;
  readonly since: number;
}

/** When a property arrived on a block (`since`) or left it (`until`). */
interface PropertyEvent {
  readonly block: string;
  readonly property: string;
  readonly since: number | null;
  readonly until: number | null;
}

/**
 * A property whose legal values changed, with the map in both directions.
 *
 * `backport` is keyed on the newer values and `forward` on the older ones, so
 * neither is the inverse of the other and neither pretends to be: the walls'
 * `tall` comes back as `true` and goes out again as `low`, because 1.15 has one
 * kind of connection and there is nothing else it can say.
 */
interface ValueChange {
  readonly properties: readonly string[];
  readonly blocks: readonly string[];
  readonly since: number;
  readonly backport: Readonly<Record<string, string>>;
  readonly forward: Readonly<Record<string, string>>;
}

